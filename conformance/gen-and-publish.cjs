const sha = (p) => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const short = (p) => sha(p).slice(0, 16);
const size = (p) => fs.statSync(p).size;

// ---------- run the harness and PARSE its output ----------
function measure(subject, label) {
  const r = spawnSync(NODE, [RUNNER, subject], { cwd: W, encoding: 'utf8', maxBuffer: 1 << 24 });
  const out = ((r.stdout || '') + (r.stderr || '')).replace(/\r\n/g, '\n');
  const num = (re) => { const m = out.match(re); return m ? Number(m[1]) : null; };
  const m = {
    label,
    exit: r.status,
    subjectBytes: size(W + '/' + subject),
    subjectSha: short(W + '/' + subject),
    smoke: /smoke control: PASS/.test(out),
    negControl: /NEGATIVE CONTROL len=40: PASS/.test(out),
    scorable: num(/corpus:\s*(\d+) scorable/),
    undeterminable: num(/corpus:\s*\d+ scorable,\s*(\d+) undeterminable/),
    agree: num(/agree:\s*(\d+)\/(\d+)/),
    total: (() => { const x = out.match(/agree:\s*\d+\/(\d+)/); return x ? Number(x[1]) : null; })(),
    acceptedInvalid: num(/accepted-invalid:\s*(\d+)/),
    rejectedValid: num(/rejected-valid:\s*(\d+)/),
    overAccepted: (() => { const x = out.match(/over-length accepted:\s*(\d+)\/(\d+)/); return x ? Number(x[1]) : null; })(),
    overTotal: (() => { const x = out.match(/over-length accepted:\s*\d+\/(\d+)/); return x ? Number(x[1]) : null; })(),
    truncated: num(/of those, TRUNCATED:\s*(\d+)/),
    verdictDisagreements: num(/VERDICT:\s*(\d+) disagreement/),
    truncationVerdict: /silent address truncation reproduced/.test(out),
  };
  // Refuse to publish numbers from a run whose controls did not both pass.
  m.trustworthy = m.smoke && m.negControl && m.exit !== 2;
  if (!m.trustworthy) {
    console.error('ABORT: ' + label + ' controls failed (smoke=' + m.smoke + ' neg=' + m.negControl + ' exit=' + m.exit + ')');
    console.error(out.slice(0, 2000));
    process.exit(2);
  }
  return m;
}

